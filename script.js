let currentLang = 'bn';

// DOM Elements
const langToggleBtn = document.getElementById('langToggleBtn');
const langLabel = document.getElementById('langLabel');
const toast = document.getElementById('toast');
const toastText = document.getElementById('toastText');
const searchInput = document.getElementById('searchInput');
const appCards = document.querySelectorAll('.app-card');
const detailsModal = document.getElementById('detailsModal');
const modalTitle = document.getElementById('modalTitle');
const modalBody = document.getElementById('modalBody');

appCards.forEach((card, index) => {
  if (index > 0) {
    card.style.display = 'none';
  }
});

// Show Toast
function showToast(message) {
  toastText.textContent = message;
  toast.classList.add('show');
  setTimeout(() => {
    toast.classList.remove('show');
  }, 3500);
}

// Download button click feedback
document.querySelectorAll('.btn-download').forEach(btn => {
  btn.addEventListener('click', (e) => {
    if (btn.getAttribute('href') === '#') {
      e.preventDefault();
      return;
    }

    const t = translations[currentLang];
    showToast(t.toastDownloading);
  });
});

// Copy link
function copyAppLink(url) {
  const fullUrl = new URL(url, window.location.href).href;
  if (navigator.clipboard) {
    navigator.clipboard.writeText(fullUrl).then(() => {
      showToast(translations[currentLang].copiedLink);
    }).catch(() => {
      showToast(translations[currentLang].copiedLink);
    });
  } else {
    showToast(translations[currentLang].copiedLink);
  }
}

// Language switch
function updateLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      if (el.tagName === 'INPUT') {
        el.placeholder = t[key];
      } else {
        el.innerHTML = t[key];
      }
    }
  });

  if (lang === 'bn') {
    langLabel.textContent = 'ENG';
  } else {
    langLabel.textContent = 'বাংলা';
  }
}

if (langToggleBtn) {
  langToggleBtn.addEventListener('click', () => {
    const newLang = currentLang === 'bn' ? 'en' : 'bn';
    updateLanguage(newLang);
  });
}

// Search Filter
if (searchInput) {
  searchInput.addEventListener('input', (e) => {
    const term = e.target.value.toLowerCase().trim();
    appCards.forEach(card => {
      const title = card.querySelector('.app-title').textContent.toLowerCase();
      const desc = card.querySelector('.app-description').textContent.toLowerCase();
      if (title.includes(term) || desc.includes(term)) {
        card.style.display = 'block';
      } else {
        card.style.display = 'none';
      }
    });
  });
}

// FAQ Accordion
document.querySelectorAll('.faq-question').forEach(q => {
  q.addEventListener('click', () => {
    const item = q.parentElement;
    item.classList.toggle('active');
  });
});

const screenshotLightbox = document.getElementById('screenshotLightbox');
const screenshotLightboxImg = document.getElementById('screenshotLightboxImg');

function openScreenshotModal(src, alt = 'Screenshot') {
  if (!screenshotLightbox || !screenshotLightboxImg) return;
  screenshotLightboxImg.src = src;
  screenshotLightboxImg.alt = alt;
  screenshotLightbox.classList.add('open');
}

function closeScreenshotModal() {
  if (!screenshotLightbox) return;
  screenshotLightbox.classList.remove('open');
  screenshotLightboxImg.src = '';
}

document.querySelectorAll('.walkthrough-card img').forEach(img => {
  img.addEventListener('click', () => {
    openScreenshotModal(img.src, img.alt || 'Screenshot');
  });
});

if (screenshotLightbox) {
  screenshotLightbox.addEventListener('click', (e) => {
    if (e.target === screenshotLightbox) closeScreenshotModal();
  });
}

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && screenshotLightbox && screenshotLightbox.classList.contains('open')) {
    closeScreenshotModal();
  }
});

